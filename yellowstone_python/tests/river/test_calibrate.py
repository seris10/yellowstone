def test_ivp_crosscheck_euler_converges_first_order():
    # Backward-Euler truncation roughly halves with the step; ratio far from 2 indicts the formulation.
    bundle = synthetic_bundle()
    coarse = ivp_crosscheck(bundle, 20000.0, 40000.0, 2.0, 25.0,
                            1.0, dt_s=1800.0, euler_dt_s=1800.0)
    fine = ivp_crosscheck(bundle, 20000.0, 40000.0, 2.0, 25.0,
                          1.0, dt_s=1800.0, euler_dt_s=900.0)
    ratio = (coarse["max_abs_diff_c"] / fine["max_abs_diff_c"])
    assert ratio > 1.5
    assert ratio < 2.5
    assert (coarse['budget_ok'])
    assert (fine['budget_ok'])


