def test_score_and_ranking_composite_score_components():
    comp = composite_score(0.5, 0.2, 1e-6, 0)
    assert comp['temperature_rmse_term'] == pytest.approx(0.5, abs=0.5 * 10 ** -(7), rel=0)
    assert comp['temperature_abs_bias_term'] == pytest.approx(0.25 * 0.2, abs=0.5 * 10 ** -(7), rel=0)
    assert comp['newton_failure_term'] == pytest.approx(0.0, abs=0.5 * 10 ** -(7), rel=0)
    assert comp['score'] == pytest.approx(comp['temperature_rmse_term'] + comp['temperature_abs_bias_term'] + comp['heat_residual_term'] + comp['newton_failure_term'], abs=0.5 * 10 ** -(7), rel=0)


def test_score_and_ranking_composite_score_penalizes_newton_failure():
    clean = composite_score(0.5, 0.0, 1e-6, 0)
    failed = composite_score(0.5, 0.0, 1e-6, 1)
    assert failed['score'] > clean['score'] + 1.0


