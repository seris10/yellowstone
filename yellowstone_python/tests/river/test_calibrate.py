def synthetic_bundle(truth=(2.0, 25.0, 1.0), days=2, dt_s=1800.0):
    """Bundle with a synthetic downstream generated by the forward model."""
    import time
    q_lat, t_lat, c_mult = truth
    t0 = time.time()
    n = int(days * 86400 // dt_s)
    grid = [t0 + i * dt_s for i in range(n + 1)]
    up_t = [[g, 10.0 + 2.0 * math.sin((g - t0) / 86400.0 * 2 * math.pi)]
            for g in grid]
    up_q = [[g, 1.0] for g in grid]
    met = [[g, 8.0 + 5.0 * math.sin((g - t0) / 86400.0 * 2 * math.pi),
            0.5, 2.0, max(0.0, 500.0 * math.sin(
                (g - t0) / 86400.0 * 2 * math.pi)), 0.2] for g in grid]
    draft = {"sites": {
        "06036805": {"series": {"temperature_c": up_t,
                                "discharge_m3_s": up_q}},
        "06036905": {"series": {"temperature_c": [], "discharge_m3_s": []}}},
        "met": {"hourly": met}}
    fwd = run_fit_forward(draft, 20000.0, 20000.0 / 0.5,
                          q_lat, t_lat, c_mult, dt_s)
    draft["sites"]["06036905"]["series"] = {
        "temperature_c": [[g, v] for g, v in zip(fwd["grid"],
                                                 fwd["modeled_c"])],
        "discharge_m3_s": [[g, 1.0 + q_lat] for g in fwd["grid"]]}
    return draft


