def test_alignment_bin_mean_and_coverage():
    pairs = [[100.0, 1.0], [105.0, 3.0], [250.0, 9.0]]
    grid = [100.0, 200.0, 300.0]
    values, coverage, count_per_bin = resample_bin_mean(pairs, grid, 100.0)
    assert values[0] == pytest.approx(2.0, abs=0.5 * 10 ** -(7), rel=0)
    assert values[1] is None
    assert values[2] == pytest.approx(9.0, abs=0.5 * 10 ** -(7), rel=0)
    assert coverage == pytest.approx(2.0 / 3.0, abs=0.5 * 10 ** -(7), rel=0)


def test_alignment_bin_mean_rejects_bad():
    with pytest.raises(ValueError):
        resample_bin_mean([[0.0, 1.0]], [], 10.0)
    with pytest.raises(ValueError):
        resample_bin_mean([[0.0, 1.0]], [0.0], 0.0)


