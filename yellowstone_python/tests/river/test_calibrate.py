def test_fit_recovery_forward_measured_series_boundary():
    bundle = synthetic_bundle()
    mean_fwd = run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                               dt_s=1800.0)
    sched_fwd = run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                                dt_s=1800.0,
                                boundary_discharge="measured_series")
    assert sched_fwd['boundary_discharge'] == 'measured_series'
    assert not (sched_fwd['discharge_variability_ignored'])
    assert sched_fwd['boundary_q_source'] == 'measured_upstream_series_schedule'
    assert isinstance(sched_fwd['boundary_q_m3_s'], dict)
    assert 'times_s' in sched_fwd['boundary_q_m3_s']
    assert 'values' in sched_fwd['boundary_q_m3_s']
    # Constant upstream discharge; the two trajectories agree to float noise.
    for m, s in zip(mean_fwd["modeled_c"], sched_fwd["modeled_c"]):
        assert m == pytest.approx(s, abs=0.5 * 10 ** -(6), rel=0)


