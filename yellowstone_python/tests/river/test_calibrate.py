def test_alignment_continuity_passes_clean_rejects_gappy():
    clean = [[float(i * 900), 10.0] for i in range(20)]
    assert check_continuity(clean, 'clean', 3600.0) == pytest.approx(900.0, abs=0.5 * 10 ** -(7), rel=0)
    gappy = clean[:5] + [[t + 20000.0, v] for t, v in clean[5:]]
    with pytest.raises(ValueError):
        check_continuity(gappy, "gappy", 3600.0)
    with pytest.raises(ValueError):
        check_continuity([[0.0, 1.0]], "single", 3600.0)



def test_dispersion_moments_of_known_gaussian():
    centers = [float(i) for i in range(200)]
    vols = [1.0] * 200
    temps = [10.0 + 5.0 * math.exp(-((x - 100.0) ** 2) / (2 * 20.0 ** 2))
             for x in centers]
    m = pulse_moments(centers, vols, temps, 10.0)
    assert m['centroid_m'] == pytest.approx(100.0, abs=0.5, rel=0)
    assert m['variance_m2'] == pytest.approx(400.0, abs=30.0, rel=0)


def test_dispersion_moments_reject_flat():
    with pytest.raises(ValueError):
        pulse_moments([0.0, 1.0], [1.0, 1.0], [5.0, 5.0], 5.0)


def test_dispersion_effective_d_tracks_specified_d():
    # Coarse channel keeps this test fast; upwind D_num ~ V*dx/2.
    lo = uniform_pulse_run(length_m=2000.0, n_cells=40,
                           dispersion_m2_s=0.0, duration_s=600.0,
                           dt_s=5.0)
    hi = uniform_pulse_run(length_m=2000.0, n_cells=40,
                           dispersion_m2_s=20.0, duration_s=600.0,
                           dt_s=5.0)
    assert lo['effective_d_m2_s'] > 0.0  # numerical floor
    assert hi['effective_d_m2_s'] - lo['effective_d_m2_s'] == pytest.approx(20.0, abs=3.0, rel=0)
    assert abs(hi['advection_error_pct']) < 5.0
    assert hi['budget']['heat_relative_residual'] <= 1e-09


