class AlignmentTests(unittest.TestCase):
    def test_bin_mean_and_coverage(self):
        pairs = [[100.0, 1.0], [105.0, 3.0], [250.0, 9.0]]
        grid = [100.0, 200.0, 300.0]
        values, coverage, count_per_bin = resample_bin_mean(pairs, grid, 100.0)
        self.assertAlmostEqual(values[0], 2.0)
        self.assertIsNone(values[1])
        self.assertAlmostEqual(values[2], 9.0)
        self.assertAlmostEqual(coverage, 2.0 / 3.0)

    def test_bin_mean_rejects_bad(self):
        with self.assertRaises(ValueError):
            resample_bin_mean([[0.0, 1.0]], [], 10.0)
        with self.assertRaises(ValueError):
            resample_bin_mean([[0.0, 1.0]], [0.0], 0.0)

    def test_interp_linear_and_clamp(self):
        pairs = [[0.0, 0.0], [10.0, 10.0]]
        self.assertAlmostEqual(interp_series(pairs, [5.0])[0], 5.0)
        self.assertAlmostEqual(interp_series(pairs, [-3.0])[0], 0.0)
        self.assertAlmostEqual(interp_series(pairs, [99.0])[0], 10.0)
        with self.assertRaises(ValueError):
            interp_series([], [1.0])

    def test_lag_recovery(self):
        base = [math.sin(i * 0.3) for i in range(60)]
        lagged = [0.0] * 4 + base[:-4]
        info = estimate_lag(base, lagged, 10.0, 200.0)
        self.assertEqual(info["lag_s"], 40.0)
        self.assertGreater(info["peak_correlation"], 0.9)

    def test_lag_rejects_constant(self):
        with self.assertRaises(ValueError):
            estimate_lag([1.0] * 10, [2.0] * 10, 5.0, 50.0)

    def test_continuity_passes_clean_rejects_gappy(self):
        clean = [[float(i * 900), 10.0] for i in range(20)]
        self.assertAlmostEqual(
            check_continuity(clean, "clean", 3600.0), 900.0)
        gappy = clean[:5] + [[t + 20000.0, v] for t, v in clean[5:]]
        with self.assertRaises(ValueError):
            check_continuity(gappy, "gappy", 3600.0)
        with self.assertRaises(ValueError):
            check_continuity([[0.0, 1.0]], "single", 3600.0)


class DispersionTests(unittest.TestCase):
    def test_moments_of_known_gaussian(self):
        centers = [float(i) for i in range(200)]
        vols = [1.0] * 200
        temps = [10.0 + 5.0 * math.exp(-((x - 100.0) ** 2) / (2 * 20.0 ** 2))
                 for x in centers]
        m = pulse_moments(centers, vols, temps, 10.0)
        self.assertAlmostEqual(m["centroid_m"], 100.0, delta=0.5)
        self.assertAlmostEqual(m["variance_m2"], 400.0, delta=30.0)

    def test_moments_reject_flat(self):
        with self.assertRaises(ValueError):
            pulse_moments([0.0, 1.0], [1.0, 1.0], [5.0, 5.0], 5.0)

    def test_effective_d_tracks_specified_d(self):
        # Coarse channel keeps this test fast; upwind D_num ~ V*dx/2.
        lo = uniform_pulse_run(length_m=2000.0, n_cells=40,
                               dispersion_m2_s=0.0, duration_s=600.0,
                               dt_s=5.0)
        hi = uniform_pulse_run(length_m=2000.0, n_cells=40,
                               dispersion_m2_s=20.0, duration_s=600.0,
                               dt_s=5.0)
        self.assertGreater(lo["effective_d_m2_s"], 0.0)  # numerical floor
        self.assertAlmostEqual(hi["effective_d_m2_s"] - lo["effective_d_m2_s"],
                               20.0, delta=3.0)
        self.assertLess(abs(hi["advection_error_pct"]), 5.0)
        self.assertLessEqual(hi["budget"]["heat_relative_residual"], 1e-9)

    def test_sweep_structure(self):
        doc = dispersion_sweep([0.0, 5.0], length_m=2000.0, n_cells=40,
                               duration_s=600.0, dt_s=5.0)
        self.assertEqual(doc["schema"], "yellowstone.dispersion_sweep.v1")
        self.assertEqual(len(doc["runs"]), 2)
        self.assertEqual(doc["runs"][1]["specified_d_m2_s"], 5.0)


def synthetic_bundle(truth=(2.0, 25.0, 1.0), days=2, dt_s=1800.0):
    """Bundle with a synthetic downstream generated by the forward model."""
    import time
    q_lat, t_lat, c_mult = truth
    t0 = time.time()
    n = int(days * 86400 // dt_s)
    grid = [t0 + i * dt_s for i in range(n + 1)]
    up_t = [[g, 10.0 + 2.0 * math.sin((g - t0) / 86400.0 * 2 * math.pi)]
            for g in grid]
    up_q = [[g, 1.0] for g in grid]
    met = [[g, 8.0 + 5.0 * math.sin((g - t0) / 86400.0 * 2 * math.pi),
            0.5, 2.0, max(0.0, 500.0 * math.sin(
                (g - t0) / 86400.0 * 2 * math.pi)), 0.2] for g in grid]
    draft = {"sites": {
        "06036805": {"series": {"temperature_c": up_t,
                                "discharge_m3_s": up_q}},
        "06036905": {"series": {"temperature_c": [], "discharge_m3_s": []}}},
        "met": {"hourly": met}}
    fwd = run_fit_forward(draft, 20000.0, 20000.0 / 0.5,
                          q_lat, t_lat, c_mult, dt_s)
    draft["sites"]["06036905"]["series"] = {
        "temperature_c": [[g, v] for g, v in zip(fwd["grid"],
                                                 fwd["modeled_c"])],
        "discharge_m3_s": [[g, 1.0 + q_lat] for g in fwd["grid"]]}
    return draft


class FitRecoveryTests(unittest.TestCase):
    def test_forward_rejects_unknown_backend(self):
        bundle = synthetic_bundle()
        with self.assertRaises(ValueError):
            run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                            dt_s=1800.0, backend="dask")

    def test_forward_is_conservative(self):
        bundle = synthetic_bundle()
        fwd = run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                              dt_s=1800.0)
        self.assertTrue(fwd["budget_ok"])
        self.assertEqual(len(fwd["modeled_c"]), len(fwd["grid"]))
        self.assertEqual(fwd["boundary_discharge"], "mean")
        self.assertTrue(fwd["discharge_variability_ignored"])

    def test_forward_measured_series_boundary(self):
        bundle = synthetic_bundle()
        mean_fwd = run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                                   dt_s=1800.0)
        sched_fwd = run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                                    dt_s=1800.0,
                                    boundary_discharge="measured_series")
        self.assertEqual(sched_fwd["boundary_discharge"], "measured_series")
        self.assertFalse(sched_fwd["discharge_variability_ignored"])
        self.assertEqual(
            sched_fwd["boundary_q_source"],
            "measured_upstream_series_schedule")
        self.assertIsInstance(sched_fwd["boundary_q_m3_s"], dict)
        self.assertIn("times_s", sched_fwd["boundary_q_m3_s"])
        self.assertIn("values", sched_fwd["boundary_q_m3_s"])
        # Constant upstream discharge; the two trajectories agree to float noise.
        for m, s in zip(mean_fwd["modeled_c"], sched_fwd["modeled_c"]):
            self.assertAlmostEqual(m, s, places=6)

    def test_forward_rejects_unknown_boundary_discharge(self):
        bundle = synthetic_bundle()
        with self.assertRaises(ValueError):
            run_fit_forward(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                            dt_s=1800.0, boundary_discharge="hydrograph")

    def test_fit_null_b_refits_when_c0_missing(self):
        bundle = synthetic_bundle()
        doc = reach_heat_fit(
            bundle, 20000.0, 40000.0,
            lateral_q_grid=[1.0, 2.0, 3.0],
            lateral_t_grid=[15.0, 25.0, 35.0],
            c_mult_grid=[0.5, 1.0, 2.0],
            spinup_s=3600.0, train_frac=0.6, dt_s=1800.0)
        names = [n["name"] for n in doc["null_models"]]
        self.assertIn("mixing_only_c0_refit", names)
        self.assertNotIn("mixing_only_c0_at_champion_laterals", names)
        boundaries = doc["champion"]["at_parameter_boundary"]
        self.assertIn("q_lat", boundaries)
        self.assertIn("at_min", boundaries["q_lat"])
        hierarchy = doc["champion"]["calibration_hierarchy"]
        self.assertIn("L3_fitted_effective", hierarchy)
        self.assertEqual(
            doc["champion"]["surface_model"]["not_identified_independently"],
            ["c_h", "c_e"])

    def test_fit_rejects_bad_arguments(self):
        bundle = synthetic_bundle()
        with self.assertRaises(ValueError):
            reach_heat_fit(bundle, 20000.0, 40000.0,
                           lateral_q_grid=[],
                           lateral_t_grid=[25.0],
                           c_mult_grid=[1.0], dt_s=1800.0)
        with self.assertRaises(ValueError):
            reach_heat_fit(bundle, 20000.0, 40000.0,
                           lateral_q_grid=[2.0],
                           lateral_t_grid=[25.0],
                           c_mult_grid=[1.0], train_frac=1.0, dt_s=1800.0)

    def test_fit_recovers_synthetic_truth(self):
        # Inverse crime: same forward model generates and fits; proves only that the optimizer/grid works.
        bundle = synthetic_bundle()
        doc = reach_heat_fit(
            bundle, 20000.0, 40000.0,
            lateral_q_grid=[1.0, 2.0, 3.0],
            lateral_t_grid=[15.0, 25.0, 35.0],
            c_mult_grid=[0.5, 1.0, 2.0],
            spinup_s=3600.0, train_frac=0.6, dt_s=1800.0)
        champ = doc["champion"]
        self.assertEqual((champ["q_lat"], champ["t_lat"], champ["c_mult"]),
                         (2.0, 25.0, 1.0))
        self.assertLess(champ["train_rmse"], 0.05)
        self.assertIn("top10_train", doc)
        self.assertEqual(doc["status"], "fitted_not_validated_single_window")


class LeastSquaresTests(unittest.TestCase):
    def test_polish_recovers_synthetic_truth(self):
        # Inverse crime again: same model generates and fits; proves optimizer machinery.
        bundle = synthetic_bundle()
        polished = least_squares_fit(
            bundle, 20000.0, 40000.0, (1.0, 15.0, 0.5),
            spinup_s=3600.0, train_frac=0.6, dt_s=1800.0)
        self.assertAlmostEqual(polished["q_lat"], 2.0, delta=0.05)
        self.assertAlmostEqual(polished["t_lat"], 25.0, delta=0.5)
        self.assertAlmostEqual(polished["c_mult"], 1.0, delta=0.05)
        self.assertLess(polished["train_rmse"], 0.05)
        self.assertTrue(polished["success"])
        self.assertLessEqual(polished["nfev"], 60)

    def test_polish_stays_in_bounds(self):
        from yellowstone_python.replay.calibrate import LS_BOUNDS
        bundle = synthetic_bundle()
        polished = least_squares_fit(
            bundle, 20000.0, 40000.0, (7.0, 55.0, 7.0),
            spinup_s=3600.0, train_frac=0.6, dt_s=1800.0)
        for knob, value in (("q_lat", polished["q_lat"]),
                            ("t_lat", polished["t_lat"]),
                            ("c_mult", polished["c_mult"])):
            lo, hi = LS_BOUNDS[knob]
            self.assertGreaterEqual(value, lo)
            self.assertLessEqual(value, hi)

    def test_polish_requires_x0(self):
        bundle = synthetic_bundle()
        with self.assertRaises(ValueError):
            least_squares_fit(bundle, 20000.0, 40000.0, None,
                              spinup_s=3600.0, train_frac=0.6,
                              dt_s=1800.0)


class SelectionTests(unittest.TestCase):
    def test_aic_bic_prefer_fit_over_null(self):
        rss_fit, rss_null, n = 10.0, 900.0, 100
        fit = aic_bic(rss_fit, n, 3)
        null0 = aic_bic(rss_null, n, 0)
        null2 = aic_bic(rss_null, n, 2)
        self.assertLess(fit["aic"], null0["aic"])
        self.assertLess(fit["bic"], null2["bic"])
        self.assertLess(null0["aic"], null2["aic"])  # same rss: k decides

    def test_aic_bic_reject_bad(self):
        with self.assertRaises(ValueError):
            aic_bic(-1.0, 100, 3)
        with self.assertRaises(ValueError):
            aic_bic(10.0, 0, 3)

    def test_aic_bic_zero_rss_perfect_fit(self):
        perfect = aic_bic(0.0, 100, 3)
        self.assertEqual(perfect["aic"], -math.inf)
        self.assertEqual(perfect["bic"], -math.inf)
        self.assertEqual(perfect["n"], 100.0)
        self.assertEqual(perfect["k"], 3.0)


class IvpCrosscheckTests(unittest.TestCase):
    def test_euler_converges_first_order(self):
        # Backward-Euler truncation roughly halves with the step; ratio far from 2 indicts the formulation.
        bundle = synthetic_bundle()
        coarse = ivp_crosscheck(bundle, 20000.0, 40000.0, 2.0, 25.0,
                                1.0, dt_s=1800.0, euler_dt_s=1800.0)
        fine = ivp_crosscheck(bundle, 20000.0, 40000.0, 2.0, 25.0,
                              1.0, dt_s=1800.0, euler_dt_s=900.0)
        ratio = (coarse["max_abs_diff_c"] / fine["max_abs_diff_c"])
        self.assertGreater(ratio, 1.5)
        self.assertLess(ratio, 2.5)
        self.assertTrue(coarse["budget_ok"])
        self.assertTrue(fine["budget_ok"])

    def test_ivp_rejects_bad_step(self):
        bundle = synthetic_bundle()
        with self.assertRaises(ValueError):
            ivp_crosscheck(bundle, 20000.0, 40000.0, 2.0, 25.0, 1.0,
                           dt_s=1800.0, euler_dt_s=1000.0)


class ScoreAndRankingTests(unittest.TestCase):
    def test_composite_score_components(self):
        comp = composite_score(0.5, 0.2, 1e-6, 0)
        self.assertAlmostEqual(
            comp["temperature_rmse_term"], 0.5)
        self.assertAlmostEqual(
            comp["temperature_abs_bias_term"], 0.25 * 0.2)
        self.assertAlmostEqual(
            comp["newton_failure_term"], 0.0)
        self.assertAlmostEqual(
            comp["score"],
            comp["temperature_rmse_term"]
            + comp["temperature_abs_bias_term"]
            + comp["heat_residual_term"]
            + comp["newton_failure_term"])

    def test_composite_score_penalizes_newton_failure(self):
        clean = composite_score(0.5, 0.0, 1e-6, 0)
        failed = composite_score(0.5, 0.0, 1e-6, 1)
        self.assertGreater(failed["score"], clean["score"] + 1.0)

    def test_score_paired_series_available_on_calibrate(self):
        out = score_paired_series([1.0, 2.0, 3.0], [1.0, 2.0, 4.0])
        self.assertIn("rmse", out)


